#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES.md from `cargo metadata --locked` (every crate in Cargo.lock, all
# platforms) plus the licence files that ship inside each crate's source.
#
#   scripts/gen-notices.sh            rewrite THIRD_PARTY_NOTICES.md
#   scripts/gen-notices.sh --check    exit 1 if the committed file is out of date (for CI)
#   scripts/gen-notices.sh --stdout   print instead of writing
#
# Needs: cargo, python3 (standard library only), a populated cargo registry (the first run downloads
# crate sources the way `cargo build` would). Output is deterministic: sorted, no timestamps.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mode="write"
case "${1:-}" in
  "") ;;
  --check) mode="check" ;;
  --stdout) mode="stdout" ;;
  *) echo "usage: $0 [--check|--stdout]" >&2; exit 2 ;;
esac

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
(cd "$root" && cargo metadata --locked --format-version 1 >"$tmp/meta.json")

# `-I` keeps the interpreter from importing anything out of the current directory.
python3 -I - "$tmp/meta.json" >"$tmp/out.md" <<'PY'
import hashlib, json, os, sys

meta = json.load(open(sys.argv[1]))
workspace = set(meta["workspace_members"])
pkgs = sorted(
    (p for p in meta["packages"] if p["id"] not in workspace),
    key=lambda p: (p["name"], p["version"]),
)
LICENSE_NAMES = ("license", "licence", "copying", "unlicense", "notice", "copyright")


def licence_files(pkg):
    base = os.path.dirname(pkg["manifest_path"])
    found = []
    if not os.path.isdir(base):
        return found
    for dirpath, dirnames, filenames in os.walk(base):
        depth = os.path.relpath(dirpath, base).count(os.sep)
        dirnames[:] = sorted(d for d in dirnames if d not in ("target", ".git") and depth < 2)
        for name in sorted(filenames):
            low = name.lower()
            rel = os.path.relpath(os.path.join(dirpath, name), base)
            in_fonts = rel.startswith("fonts" + os.sep) and low.endswith(".txt")
            if low.startswith(LICENSE_NAMES) or in_fonts:
                if low.endswith((".rs", ".toml", ".json", ".py", ".sh")):
                    continue
                found.append(rel)
    return found


texts = {}  # sha256 -> (text, [(name, version, rel)])
missing = []
for p in pkgs:
    files = licence_files(p)
    if not files:
        missing.append(p)
    for rel in files:
        path = os.path.join(os.path.dirname(p["manifest_path"]), rel)
        try:
            data = open(path, "rb").read().decode("utf-8", "replace").replace("\r\n", "\n").strip()
        except OSError:
            continue
        if not data:
            continue
        h = hashlib.sha256(data.encode()).hexdigest()
        entry = texts.setdefault(h, (data, []))
        entry[1].append((p["name"], p["version"], rel))

out = []
w = out.append
w("# Third-party notices\n")
w("<!-- Generated by scripts/gen-notices.sh from `cargo metadata --locked`; do not edit by hand. -->\n")
w(
    "GeekBridge's own source licence is **not chosen yet** (see `docs/licence-decision.md`). The Rust "
    "crates below are statically linked into the GeekBridge binaries and the Android native library "
    "(which crates end up in which binary depends on the target platform; this list is the union over "
    "Linux, Windows, macOS and Android). The Android app itself has no third-party Java/Kotlin "
    "runtime dependencies and bundles no fonts or images from other projects; the dot-matrix UI is "
    "drawn in code and the icons are hand-drawn vector paths.\n"
)
w(f"{len(pkgs)} third-party crates. The licence expression is the one the crate declares in its "
  "`Cargo.toml`; where it offers a choice (`OR`), GeekBridge relies on the permissive alternative "
  "(MIT, Apache-2.0 or Zlib), never the LGPL one.\n")

w("## Bundled fonts (egui default fonts)\n")
w(
    "The desktop apps (`bridge-apps`, via `eframe` with the `default_fonts` feature) embed the fonts "
    "from `epaint_default_fonts`. Their licences are reproduced in the text section below "
    "(`epaint_default_fonts`, `fonts/…`):\n"
)
w("- Hack Regular: MIT and Bitstream Vera licence (`Hack-Regular.txt`)")
w("- Ubuntu Light: Ubuntu Font Licence 1.0 (`UFL.txt`). Modified versions must not use the "
  "\"Ubuntu\" name; we ship it unmodified.")
w("- Noto Emoji Regular: SIL Open Font Licence 1.1 (`OFL.txt`)")
w("- emoji-icon-font: MIT (`emoji-icon-font-mit-license.txt`)\n")
w("## Other notes\n")
w("- `webpki-roots` (CDLA-Permissive-2.0) embeds the Mozilla CA bundle as data; attribution is satisfied "
  "by this notice.")
w("- `ring` carries a combined ISC / OpenSSL-style licence (its `LICENSE` text is reproduced below).")
w("- `r-efi` is offered under `MIT OR Apache-2.0 OR LGPL-2.1-or-later`; it is UEFI-only and not linked "
  "into any GeekBridge binary, and we would elect MIT/Apache-2.0 regardless.")
w("- `clipboard-win` / `error-code` (BSL-1.0) are Windows-only and permissive (no notice is required "
  "for binary distribution, the text is included anyway).\n")

w("## Crates\n")
w("| Crate | Version | Licence | Source |")
w("|---|---|---|---|")
for p in pkgs:
    lic = (p["license"] or ("see " + p["license_file"] if p.get("license_file") else "UNKNOWN")).replace("|", "\\|")
    w(f"| {p['name']} | {p['version']} | {lic} | {p.get('repository') or p.get('homepage') or ''} |")
w("")

if missing:
    w("### Crates that ship no licence file in their package\n")
    w("These crates (mostly workspace members of egui, objc2, windows-rs and similar monorepos whose "
      "licence files live at the repository root) are published without a licence file. Their licence is "
      "the declared expression above (standard texts: https://spdx.org/licenses/) and the copyright "
      "holders are named in the linked repository. Before a public release, consider replacing this "
      "section with `cargo about` output, which fetches those root files (docs/supply-chain.md).\n")
    w(", ".join(f"{p['name']} {p['version']}" for p in missing) + "\n")

w("## Licence texts\n")
w("Identical texts are listed once, followed by the crates (and file) they came from.\n")
ordered = sorted(texts.items(), key=lambda kv: (sorted(kv[1][1])[0], kv[0]))
for i, (_, (text, users)) in enumerate(ordered, 1):
    users = sorted(set(users))
    names = ", ".join(f"{n} {v} (`{rel}`)" for n, v, rel in users)
    w(f"### {i}. {names}\n")
    w("```text")
    w(text.replace("```", "'''"))
    w("```\n")

sys.stdout.write("\n".join(out) + "\n")
PY

dest="$root/THIRD_PARTY_NOTICES.md"
case "$mode" in
  stdout) cat "$tmp/out.md" ;;
  check)
    if ! cmp -s "$tmp/out.md" "$dest"; then
      echo "THIRD_PARTY_NOTICES.md is out of date: run scripts/gen-notices.sh and commit the result" >&2
      exit 1
    fi
    echo "THIRD_PARTY_NOTICES.md is up to date" ;;
  write) cp "$tmp/out.md" "$dest"; echo "wrote $dest ($(wc -c <"$dest") bytes)" ;;
esac
