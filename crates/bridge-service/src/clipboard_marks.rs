//! Platform-neutral clipboard logic for Windows and macOS, kept free of OS calls so it is tested on
//! Linux: the "this is a secret" markers password managers put on a copy, and the UTF-16 conversion
//! the Windows clipboard uses. The OS bindings live in `clipboard_win.rs` / `clipboard_mac.rs`.
//!
//! Sources of the markers:
//! * Windows: Microsoft's clipboard-history documentation (`CanIncludeInClipboardHistory`,
//!   `CanUploadToCloudClipboard`, DWORD 0 means "do not"), and the older conventions
//!   `ExcludeClipboardContentFromMonitorProcessing` and `Clipboard Viewer Ignore` (presence alone).
//! * macOS: nspasteboard.org (`org.nspasteboard.ConcealedType`, `TransientType`, `AutoGeneratedType`)
//!   and 1Password's own type `com.agilebits.onepassword`.

use bridge_core::clipboard::Sensitivity;

/// One format on the Windows clipboard: its registered name (None for the predefined `CF_*`
/// formats) and, for the formats that carry a DWORD flag, its value.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WinFormat {
    pub name: Option<String>,
    pub dword: Option<u32>,
}

/// Registered formats whose mere presence marks the content as not to be recorded.
pub const WIN_PRESENCE_MARKS: &[&str] = &[
    "ExcludeClipboardContentFromMonitorProcessing",
    "Clipboard Viewer Ignore",
];
/// Registered formats that carry a DWORD; `0` means "keep this out of history / the cloud".
pub const WIN_FLAG_MARKS: &[&str] = &["CanIncludeInClipboardHistory", "CanUploadToCloudClipboard"];

/// Does reading this format's value matter for [`windows_sensitivity`]?
pub fn win_wants_value(name: &str) -> bool {
    WIN_FLAG_MARKS.iter().any(|m| m.eq_ignore_ascii_case(name))
}

/// Windows: sensitive when a presence mark is there, or a flag mark carries 0. A flag format with
/// a non-zero value (or an unreadable one) is not a mark: apps do set it to 1 on purpose.
pub fn windows_sensitivity(formats: &[WinFormat]) -> Sensitivity {
    let marked = formats.iter().any(|f| {
        let Some(name) = f.name.as_deref() else {
            return false;
        };
        WIN_PRESENCE_MARKS
            .iter()
            .any(|m| m.eq_ignore_ascii_case(name))
            || (win_wants_value(name) && f.dword == Some(0))
    });
    if marked {
        Sensitivity::Sensitive
    } else {
        Sensitivity::Normal
    }
}

/// Pasteboard types that mark a macOS copy as secret, transient or machine-made.
pub const MAC_MARKS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

/// macOS: sensitive when any pasteboard type is one of [`MAC_MARKS`].
pub fn macos_sensitivity<S: AsRef<str>>(types: &[S]) -> Sensitivity {
    if types
        .iter()
        .any(|t| MAC_MARKS.iter().any(|m| m == &t.as_ref()))
    {
        Sensitivity::Sensitive
    } else {
        Sensitivity::Normal
    }
}

/// Text as the NUL-terminated UTF-16 `CF_UNICODETEXT` wants it. Interior NULs would cut the text
/// short for every reader, so they are dropped.
pub fn utf16_for_clipboard(text: &str) -> Vec<u16> {
    text.chars()
        .filter(|&c| c != '\0')
        .flat_map(|c| {
            let mut b = [0u16; 2];
            c.encode_utf16(&mut b).to_vec()
        })
        .chain(std::iter::once(0))
        .collect()
}

/// `CF_UNICODETEXT` data back to a string: up to the first NUL (or the end), `None` when it holds
/// an unpaired surrogate (not valid text, same as the UTF-8 backends' `NotUtf8`).
pub fn utf16_from_clipboard(units: &[u16]) -> Option<String> {
    let end = units.iter().position(|&u| u == 0).unwrap_or(units.len());
    String::from_utf16(&units[..end]).ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reg(name: &str, dword: Option<u32>) -> WinFormat {
        WinFormat {
            name: Some(name.into()),
            dword,
        }
    }
    const CF_TEXT: WinFormat = WinFormat {
        name: None,
        dword: None,
    };

    #[test]
    fn windows_plain_copy_is_normal() {
        let f = [
            CF_TEXT,
            reg("HTML Format", None),
            reg("Rich Text Format", None),
        ];
        assert_eq!(windows_sensitivity(&f), Sensitivity::Normal);
        assert_eq!(windows_sensitivity(&[]), Sensitivity::Normal);
    }

    #[test]
    fn windows_presence_marks_are_sensitive_in_any_case() {
        for m in WIN_PRESENCE_MARKS {
            assert_eq!(
                windows_sensitivity(&[CF_TEXT, reg(m, None)]),
                Sensitivity::Sensitive,
                "{m}"
            );
        }
        let f = [reg("excludeclipboardcontentfrommonitorprocessing", None)];
        assert_eq!(windows_sensitivity(&f), Sensitivity::Sensitive);
    }

    #[test]
    fn windows_flag_marks_need_a_zero_value() {
        for m in WIN_FLAG_MARKS {
            assert_eq!(
                windows_sensitivity(&[reg(m, Some(0))]),
                Sensitivity::Sensitive
            );
            assert_eq!(windows_sensitivity(&[reg(m, Some(1))]), Sensitivity::Normal);
            assert_eq!(windows_sensitivity(&[reg(m, None)]), Sensitivity::Normal);
        }
    }

    /// What KeePass / Bitwarden / 1Password put on the clipboard for a password.
    #[test]
    fn windows_password_manager_fixture() {
        let f = [
            CF_TEXT,
            reg("ExcludeClipboardContentFromMonitorProcessing", None),
            reg("CanIncludeInClipboardHistory", Some(0)),
            reg("CanUploadToCloudClipboard", Some(0)),
        ];
        assert_eq!(windows_sensitivity(&f), Sensitivity::Sensitive);
    }

    #[test]
    fn windows_predefined_format_never_matches_by_name() {
        // A predefined format has no name; it cannot be mistaken for a mark.
        assert_eq!(windows_sensitivity(&[CF_TEXT]), Sensitivity::Normal);
        assert!(win_wants_value("canuploadtocloudclipboard"));
        assert!(!win_wants_value("HTML Format"));
    }

    #[test]
    fn macos_marks() {
        assert_eq!(
            macos_sensitivity(&["public.utf8-plain-text", "public.html"]),
            Sensitivity::Normal
        );
        let none: [&str; 0] = [];
        assert_eq!(macos_sensitivity(&none), Sensitivity::Normal);
        for m in MAC_MARKS {
            assert_eq!(
                macos_sensitivity(&["public.utf8-plain-text", m]),
                Sensitivity::Sensitive,
                "{m}"
            );
        }
        let owned = vec![
            "public.utf8-plain-text".to_owned(),
            "org.nspasteboard.ConcealedType".to_owned(),
        ];
        assert_eq!(macos_sensitivity(&owned), Sensitivity::Sensitive);
        // Exact match: a lookalike is not a mark.
        assert_eq!(
            macos_sensitivity(&["org.nspasteboard.ConcealedTypeX"]),
            Sensitivity::Normal
        );
    }

    #[test]
    fn utf16_roundtrip_keeps_accents_emoji_and_cjk() {
        for s in [
            "plain",
            "Zażółć gęślą jaźń",
            "naïve café",
            "日本語",
            "👍🏽 ok",
            "a\r\nb",
        ] {
            let units = utf16_for_clipboard(s);
            assert_eq!(units.last(), Some(&0), "NUL-terminated");
            assert_eq!(utf16_from_clipboard(&units).as_deref(), Some(s));
        }
    }

    #[test]
    fn utf16_exact_units() {
        assert_eq!(utf16_for_clipboard("é"), vec![0x00E9, 0]);
        assert_eq!(utf16_for_clipboard("😀"), vec![0xD83D, 0xDE00, 0]);
        assert_eq!(utf16_for_clipboard(""), vec![0]);
    }

    #[test]
    fn utf16_interior_nul_is_dropped_and_decoding_stops_at_nul() {
        assert_eq!(
            utf16_for_clipboard("a\0b"),
            vec![b'a' as u16, b'b' as u16, 0]
        );
        assert_eq!(utf16_from_clipboard(&[0x61, 0, 0x62]).as_deref(), Some("a"));
        assert_eq!(utf16_from_clipboard(&[0x61, 0x62]).as_deref(), Some("ab"));
    }

    #[test]
    fn utf16_unpaired_surrogate_is_refused() {
        assert_eq!(utf16_from_clipboard(&[0xD83D, 0x61, 0]), None);
    }
}
