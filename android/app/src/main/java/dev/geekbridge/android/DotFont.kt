/**
 * A 5x7 dot-matrix font drawn from code (original glyph shapes, no font file). Each glyph is seven rows of
 * '1' (lit) and '0' (dark); glyph width is the row length, so punctuation is narrow. Lower case is shown as
 * upper case; characters without a glyph render as a blank cell.
