    private val BLANK = g("00000", "00000", "00000", "00000", "00000", "00000", "00000")

    fun glyph(c: Char): Array<String> = GLYPHS[c.uppercaseChar()] ?: BLANK

    /** Columns taken by [s] on one line, including the one-column gap between glyphs. */
    fun columns(s: CharSequence): Int {
        if (s.isEmpty()) return 0
        var n = 0
        for (c in s) n += glyph(c)[0].length + 1
        return n - 1
    }

    /** True when the dot at ([col], [row]) of [s] is lit (col counted from the left of the text). */
    fun isLit(s: CharSequence, col: Int, row: Int): Boolean {
        var x = 0
        for (c in s) {
            val g = glyph(c)
            val w = g[0].length
            if (col < x + w) return g[row][col - x] == '1'
            x += w + 1
            if (col < x) return false
        }
        return false
    }

    /**
     * The whole lit/dark grid of [s] ([ROWS] rows, [columns] wide), computed once so a view's draw loop reads an array
     * instead of scanning the string for every dot ([isLit] is O(length) and `glyph` allocates a boxed key).
     */
    fun litGrid(s: CharSequence): Array<BooleanArray> {
        val cols = columns(s)
        val grid = Array(ROWS) { BooleanArray(cols) }
        var x = 0
        for (c in s) {
            val g = glyph(c)
            val w = g[0].length
            for (row in 0 until ROWS) for (i in 0 until w) if (g[row][i] == '1') grid[row][x + i] = true
            x += w + 1
        }
        return grid
    }
}
